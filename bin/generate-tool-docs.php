<?php
/**
 * Regenerate docs/TOOLS.md from the live tool registry.
 *
 * Run on a development site where Site Manager and every integration
 * plugin (ACF, Yoast SEO, WooCommerce, Gravity Forms, WPForms, Contact
 * Form 7, Redirection, Elementor) are active, so all tools are registered:
 *
 *     wp eval-file wp-content/plugins/site-manager/bin/generate-tool-docs.php
 *
 * Integrations that aren't active are listed as missing at the end of the
 * output so an incomplete file isn't committed by accident.
 *
 * @package Site_Manager
 */

if ( ! defined( 'ABSPATH' ) || ! class_exists( 'Site_Manager_Registry' ) ) {
	fwrite( STDERR, "Run with: wp eval-file <path>/bin/generate-tool-docs.php\n" );
	return;
}

$registry   = Site_Manager_Registry::instance();
$categories = $registry->categories();
$by_cat     = $registry->by_category();
$gates      = Site_Manager_Settings::gates();

// GitHub heading anchors: lowercase, drop punctuation, spaces become hyphens.
$anchor = function ( $heading ) {
	return str_replace( ' ', '-', preg_replace( '/[^a-z0-9 \-]/', '', strtolower( $heading ) ) );
};

$cell = function ( $text ) {
	return str_replace( array( '|', "\n" ), array( '\|', ' ' ), (string) $text );
};

$md   = array();
$md[] = '# Tool reference';
$md[] = '';
$md[] = '<!-- Generated by bin/generate-tool-docs.php — do not edit by hand. -->';
$md[] = '';
$md[] = sprintf( 'Site Manager %s exposes **%d tools** in %d groups. Integration groups appear only when their plugin is active. Every tool requires the `manage_options` capability; a few also require the matching WordPress capability noted below.', SITE_MANAGER_VERSION, count( $registry->all() ), count( $categories ) );
$md[] = '';
$md[] = 'Legend: **read** — no changes · **write** — changes the site · **destructive** — deletes or overwrites data (clients should confirm first) · **external** — contacts other servers or sends email · **gated** — off until enabled in Settings → Site Manager → Tools. Required parameters are in bold.';
$md[] = '';
$md[] = '## Groups';
$md[] = '';
foreach ( $categories as $slug => $cat ) {
	$count = isset( $by_cat[ $slug ] ) ? count( $by_cat[ $slug ] ) : 0;
	$md[]  = sprintf( '- [%s](#%s) (%d) — %s', $cat['label'], $anchor( $cat['label'] ), $count, $cat['description'] );
}
$md[] = '';

foreach ( $categories as $slug => $cat ) {
	$md[] = '## ' . $cat['label'];
	$md[] = '';
	$md[] = $cat['description'];
	$md[] = '';
	$md[] = '| Tool | Type | Parameters | Description |';
	$md[] = '| --- | --- | --- | --- |';
	foreach ( isset( $by_cat[ $slug ] ) ? $by_cat[ $slug ] : array() as $name => $tool ) {
		$type = array( $tool['writes'] ? 'write' : 'read' );
		if ( $tool['destructive'] ) {
			$type[] = 'destructive';
		}
		if ( $tool['open_world'] ) {
			$type[] = 'external';
		}
		if ( $tool['gate'] ) {
			$type[] = 'gated (' . strtolower( $gates[ $tool['gate'] ]['label'] ) . ')';
		}
		if ( $tool['capability'] !== 'manage_options' ) {
			$type[] = 'needs `' . $tool['capability'] . '`';
		}
		$schema   = $tool['input_schema'];
		$required = isset( $schema['required'] ) ? (array) $schema['required'] : array();
		$params   = array();
		foreach ( array_keys( (array) $schema['properties'] ) as $param ) {
			$params[] = in_array( $param, $required, true ) ? '**' . $param . '**' : $param;
		}
		$md[] = sprintf( '| `%s` | %s | %s | %s |', $name, implode( ', ', $type ), $params ? implode( ', ', $params ) : '—', $cell( $tool['description'] ) );
	}
	$md[] = '';
}

$file = SITE_MANAGER_DIR . '/docs/TOOLS.md';
wp_mkdir_p( dirname( $file ) );
file_put_contents( $file, implode( "\n", $md ) );

$missing = array();
foreach ( site_manager_integrations() as $slug => $class ) {
	if ( ! $class::is_active() ) {
		$missing[] = $slug;
	}
}
fwrite( STDERR, sprintf( "Wrote %s (%d tools).\n", $file, count( $registry->all() ) ) );
if ( $missing ) {
	fwrite( STDERR, 'Not active, so not documented: ' . implode( ', ', $missing ) . "\n" );
}
